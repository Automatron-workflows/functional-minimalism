import test from 'node:test';
import assert from 'node:assert/strict';
import {filmFrame,mayAdvance,duration} from '../src/timeline.mjs';
import {zipFiles} from '../scripts/package.mjs';
test('illustration timing stacks the drafts, composes the result, then restarts',()=>{
 const opening=filmFrame(0);
 assert.equal(opening.stage,'source');
 assert.deepEqual(opening.drafts,[false,false,false,false]);
 assert.equal(opening.result,false);
 assert.equal(opening.fading,false);
 assert.deepEqual(filmFrame(500).drafts,[true,false,false,false]);
 assert.deepEqual(filmFrame(1200).drafts,[true,true,false,false]);
 const stacked=filmFrame(1900);
 assert.deepEqual(stacked.drafts,[true,true,true,true]);
 assert.equal(stacked.result,false);
 assert.equal(stacked.stage,'source');
 assert.equal(filmFrame(2620).stage,'compose');
 const composing=filmFrame(3300);
 assert.equal(composing.stage,'compose');
 assert.equal(composing.result,true);
 const settled=filmFrame(5000);
 assert.equal(settled.stage,'remember');
 assert.deepEqual(settled.drafts,[true,true,true,true]);
 assert.equal(settled.result,true);
 assert.equal(filmFrame(duration-1100).fading,true);
 assert.equal(filmFrame(duration).stage,'source');
 assert.equal(filmFrame(NaN).stage,'source');
 assert.deepEqual(filmFrame(NaN).drafts,[false,false,false,false]);
});
test('film stops while paused, hidden, offscreen or behind an open dialog',()=>{const active={playing:true,hidden:false,visible:true,dialogOpen:false};assert.ok(mayAdvance(active));for(const [key,value] of [['playing',false],['hidden',true],['visible',false],['dialogOpen',true]])assert.equal(mayAdvance({...active,[key]:value}),false);});
test('source archive rejects traversal paths',()=>{assert.throws(()=>zipFiles([{name:'../outside',data:'x'}]),/Unsafe/);assert.throws(()=>zipFiles([{name:'/outside',data:'x'}]),/Unsafe/);});
