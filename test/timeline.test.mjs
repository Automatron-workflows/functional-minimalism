import test from 'node:test';
import assert from 'node:assert/strict';
import {filmFrame,mayAdvance,duration} from '../src/timeline.mjs';
import {zipFiles} from '../scripts/package.mjs';
test('illustration timing cycles each model through the wipe, then settles',()=>{
 const opening=filmFrame(0);
 assert.equal(opening.stage,'source');
 assert.equal(opening.model,'claude');
 assert.equal(opening.wipe,0);
 assert.equal(opening.settled,false);
 assert.equal(opening.done,0);
 assert.equal(opening.fading,false);
 const scanning=filmFrame(1850);
 assert.equal(scanning.stage,'compose');
 assert.equal(scanning.model,'claude');
 assert.ok(scanning.wipe>0&&scanning.wipe<1);
 assert.equal(scanning.done,0);
 const cut=filmFrame(2300);
 assert.equal(cut.stage,'result');
 assert.equal(cut.model,'claude');
 assert.equal(cut.done,1);
 assert.equal(filmFrame(2600).model,'chatgpt');
 assert.equal(filmFrame(2600).stage,'source');
 assert.equal(filmFrame(2600).done,1);
 assert.equal(filmFrame(5200).model,'kimi');
 assert.equal(filmFrame(7800).model,'deepseek');
 const settled=filmFrame(10400);
 assert.equal(settled.stage,'remember');
 assert.equal(settled.model,'all');
 assert.equal(settled.wipe,1);
 assert.equal(settled.settled,true);
 assert.equal(settled.done,4);
 assert.equal(filmFrame(duration-1100).fading,true);
 const restarted=filmFrame(duration);
 assert.equal(restarted.stage,'source');
 assert.equal(restarted.model,'claude');
 assert.equal(restarted.wipe,0);
 assert.equal(filmFrame(NaN).model,'claude');
});
test('film stops while paused, hidden, offscreen or behind an open dialog',()=>{const active={playing:true,hidden:false,visible:true,dialogOpen:false};assert.ok(mayAdvance(active));for(const [key,value] of [['playing',false],['hidden',true],['visible',false],['dialogOpen',true]])assert.equal(mayAdvance({...active,[key]:value}),false);});
test('source archive rejects traversal paths',()=>{assert.throws(()=>zipFiles([{name:'../outside',data:'x'}]),/Unsafe/);assert.throws(()=>zipFiles([{name:'/outside',data:'x'}]),/Unsafe/);});
